const A: [f64; 7] = [-0.5, -0.6666666666666679, 0.5000000000000007, 0.7999999995323976, -0.6666666663487739, -1.142909628459501, 1.0000415263675542];

/// ln x as a double word with about 15 bits beyond an f64's, for a positive x, subnormals included. 0 gives -∞, and ∞ and NaN give
/// themselves. It's inlined always: LLVM would otherwise leave it out of line, which would stop the loops that call it vectorizing.
#[inline(always)]
pub(crate) fn ln<const FUSED: bool>(x: f64) -> Double<f64> {
    let ix = if x < f64::MIN_POSITIVE { (x * 4503599627370496.0).to_bits().wrapping_sub(52 << 52) } else { x.to_bits() };
    let (tmp, k, iz) = split(ix, OFF);
    let i = (tmp >> 45) as usize & 127;
    let (z, invc) = (f64::from_bits(iz), INVC[i]);
    // Without FMA, z splits into a high part with 21 bits and the rest, so that rhi and rhi² are exact.
    let (r, rhi, rlo) = if FUSED {
        let r = z.mla::<true>(invc, -1.0);
        (r, r, 0.0)
    } else {
        let zhi = f64::from_bits(iz.wrapping_add(1 << 31) & (!0 << 32));
        let (rhi, rlo) = (zhi * invc - 1.0, (z - zhi) * invc);
        (rhi + rlo, rhi, rlo)
    };
    let t1 = k.mla::<FUSED>(LN2.0, LOGC[i]);
    let t2 = t1 + r;
    let lo1 = k.mla::<FUSED>(LN2.1, LOGC_TAIL[i]);
    let lo2 = t1 - t2 + r;
    let (ar, ar2) = (A[0] * r, r * (A[0] * r));
    let (hi, lo3, lo4) = if FUSED {
        let hi = t2 + ar2;
        (hi, ar.mla::<true>(r, -ar2), t2 - hi + ar2)
    } else {
        let arhi = A[0] * rhi;
        let hi = t2 + rhi * arhi;
        (hi, rlo * (ar + arhi), t2 - hi + rhi * arhi)
    };
    let p = r.mla::<FUSED>(A[6], A[5]).mla::<FUSED>(ar2, r.mla::<FUSED>(A[4], A[3])).mla::<FUSED>(ar2, r.mla::<FUSED>(A[2], A[1])) * (r * ar2);
    let lo = lo1 + lo2 + lo3 + lo4 + p;
    let y = Double::new(hi + lo, hi - (hi + lo) + lo);
    let y = if x.is_nan() | (x == f64::INFINITY) { Double::new(x, 0.0) } else { y };
    if x == 0.0 { Double::new(f64::NEG_INFINITY, 0.0) } else { y }
}

